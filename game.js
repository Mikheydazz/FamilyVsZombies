function нарисоватьКарты() {
  for (const карта of игра.карты) {
    const описание = ПЕРСОНАЖИ[карта.тип];
    const перезарядка = игра.перезарядка[карта.тип] || 0;
    const хватаетЭнергии = игра.энергия >= описание.стоимость;
    const доступна = хватаетЭнергии && перезарядка <= 0;
    const выбрана = игра.выбраннаяКарта === карта.тип;

    скруглённыйПрямоугольник(карта.x, карта.y, карта.ширина, карта.высота, 12,
      выбрана ? '#f3d98a' : '#d6c49a');
    скруглённыйПрямоугольник(карта.x + 4, карта.y + 4, карта.ширина - 8, карта.высота - 26, 9, '#8fbf62');

    // Портрет персонажа
    контекст.save();
    контекст.beginPath();
    контекст.rect(карта.x + 4, карта.y + 4, карта.ширина - 8, карта.высота - 26);
    контекст.clip();
    нарисоватьПортрет(карта.тип, карта.x + карта.ширина / 2, карта.y + 44, 0.5);
    контекст.restore();

    // Имя
    контекст.fillStyle = 'rgba(30, 22, 10, 0.85)';
    контекст.fillRect(карта.x + 4, карта.y + карта.высота - 22, карта.ширина - 8, 18);
    const размерИмени = описание.название.length > 9 ? 11 : 13;
    надпись(описание.название, карта.x + карта.ширина / 2,
      карта.y + карта.высота - 13, размерИмени, '#ffeec2');

    // Стоимость
    круг(карта.x + карта.ширина - 19, карта.y + 18, 14, хватаетЭнергии ? '#ffd83d' : '#9a9a9a');
    надпись(String(описание.стоимость), карта.x + карта.ширина - 19, карта.y + 19, 15, '#4a3505');

    if (!хватаетЭнергии) {
      скруглённыйПрямоугольник(карта.x, карта.y, карта.ширина, карта.высота, 12, 'rgba(20, 20, 30, 0.45)');
    }

    // Перезарядка: тёмная полоса спадает сверху вниз
    if (перезарядка > 0) {
      const доля = ограничить(перезарядка / описание.перезарядка, 0, 1);
      контекст.save();
      путьСкруглённогоПрямоугольника(карта.x, карта.y, карта.ширина, карта.высота, 12);
      контекст.clip();
      контекст.fillStyle = 'rgba(10, 14, 25, 0.62)';
      контекст.fillRect(карта.x, карта.y, карта.ширина, карта.высота * доля);
      контекст.restore();
      надпись(перезарядка.toFixed(1), карта.x + карта.ширина / 2, карта.y + 34, 20, '#ffffff');
    }

    контекст.strokeStyle = выбрана ? '#fff2a8' : 'rgba(60, 40, 15, 0.65)';
    контекст.lineWidth = выбрана ? 4 : 2;
    путьСкруглённогоПрямоугольника(карта.x, карта.y, карта.ширина, карта.высота, 12);
    контекст.stroke();
  }
}

