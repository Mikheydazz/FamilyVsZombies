/** Крест из двух перекладин — «снаряд» дождя Даши. */
function нарисоватьКрест(x, y, размер) {
  const толщина = Math.max(2, размер * 0.4);
  контекст.fillStyle = '#fffdf0';
  контекст.fillRect(x - толщина / 2, y - размер / 2, толщина, размер);
  контекст.fillRect(x - размер / 2, y - толщина / 2, размер, толщина);
}

/** Устойчивое «случайное» 0..1 по зерну — кресты не мерцают между кадрами. */
function псевдоСлучайное(зерно) {
  const значение = Math.sin(зерно * 12.9898) * 43758.5453;
  return значение - Math.floor(значение);
}

/** Дождь из крестов в трёх вертикальных линиях вокруг Даши. */
