function нарисоватьРастение(растение) {
  контекст.save();
  контекст.translate(растение.x, растение.y);
  контекст.scale(МАСШТАБ_ПЕРСОНАЖА, МАСШТАБ_ПЕРСОНАЖА);

  контекст.beginPath();
  контекст.ellipse(0, 34, 26, 8, 0, 0, Math.PI * 2);
  контекст.fillStyle = 'rgba(0, 0, 0, 0.18)';
  контекст.fill();

  if (растение.вспышка > 0) контекст.globalAlpha = 0.55;

  // Усиленные Арсением растения подсвечиваются голубым
  if (растение.усилен && (растение.тип === 'вигголайф' || растение.тип === 'даша')) {
    контекст.globalAlpha = 0.3 + Math.sin(игра.время * 6 + растение.фаза) * 0.12;
    круг(0, 0, 30, '#7fd7ff');
    контекст.globalAlpha = растение.вспышка > 0 ? 0.55 : 1;
  }

  // Пока на газоне Лебони, стрелки гороха подсвечиваются зелёным
  if ((растение.тип === 'тимофей' || растение.тип === 'софья') && естьЛебони()) {
    контекст.globalAlpha = 0.26 + Math.sin(игра.время * 6 + растение.фаза) * 0.1;
    круг(0, 0, 30, '#9dffb0');
    контекст.globalAlpha = растение.вспышка > 0 ? 0.55 : 1;
  }

  if (растение.тип === 'алексей') нарисоватьАлексея(игра.время, растение.фаза);
  if (растение.тип === 'софья') нарисоватьСофью(игра.время, растение.фаза);
  if (растение.тип === 'тимофей') нарисоватьТимофея(игра.время, растение.фаза, растение.выстрел);
  if (растение.тип === 'вигголайф') {
    нарисоватьВигголайфа(игра.время, растение.фаза,
      ограничить(растение.запал / ВРЕМЯ_ЗАПАЛА, 0, 1));
  }
  if (растение.тип === 'мелон') нарисоватьМелона(игра.время, растение.фаза, растение.выстрел);
  if (растение.тип === 'заруд') нарисоватьЗаруда(игра.время, растение.фаза, растение.режим);
  if (растение.тип === 'антон') нарисоватьАнтона(игра.время, растение.фаза, растение.выстрел);
  if (растение.тип === 'даша') {
    нарисоватьДашу(игра.время, растение.фаза,
      ограничить(растение.таймер / (растение.длительностьДождя || ДЛИТЕЛЬНОСТЬ_ДОЖДЯ_ДАШИ), 0, 1));
  }
  if (растение.тип === 'арсений') {
    нарисоватьАрсения(игра.время, растение.фаза,
      ограничить(растение.таймер / ВРЕМЯ_АРСЕНИЯ, 0, 1));
  }
  if (растение.тип === 'вии') {
    нарисоватьВии(игра.время, растение.фаза,
      ограничить(растение.таймер / ВРЕМЯ_ПРЕВРАЩЕНИЯ_ВИИ, 0, 1));
  }
  if (растение.тип === 'кактус') {
    нарисоватьКактус(игра.время, растение.фаза,
      ограничить(растение.таймер / ВРЕМЯ_ЖИЗНИ_КАКТУСА, 0, 1));
  }
  if (растение.тип === 'колобок') нарисоватьКолобка(игра.время, растение.фаза, 0);
  if (растение.тип === 'турка') нарисоватьТурку(игра.время, растение.фаза);
  if (растение.тип === 'даникс') {
    const прогресс = прогрессПрыжкаДаникса(растение);

    // В прыжке Даникс летит по дуге к намеченному зомби и заваливается вперёд
    контекст.save();
    if (прогресс > 0) {
      const цельX = растение.цель ? растение.цель.x : растение.x;
      контекст.translate((цельX - растение.x) * прогресс,
        -Math.sin(прогресс * Math.PI) * ВЫСОТА_ПРЫЖКА_ДАНИКСА);
      контекст.rotate(прогресс * 0.8);
    }
    нарисоватьДаникса(игра.время, растение.фаза);
    контекст.restore();
  }
  if (растение.тип === 'даниксбромс') нарисоватьДаниксаБроМс(игра.время, растение.фаза);
  if (растение.тип === 'квек') {
    нарисоватьКвек(игра.время, растение.фаза, растение.взлетела,
      растение.взлетела ? ВЫСОТА_ПОЛЁТА_КВЕК : 0);
  }
  if (растение.тип === 'лебони') {
    нарисоватьЛебони(игра.время, растение.фаза,
      ограничить(растение.таймер / ВРЕМЯ_ЛЕБОНИ, 0, 1));
  }

  контекст.globalAlpha = 1;

  if (растение.вспышка > 0) {
    контекст.globalAlpha = ограничить(растение.вспышка * 2, 0, 0.5);
    круг(0, -6, 34, '#ff5a4a');
    контекст.globalAlpha = 1;
  }

  контекст.restore();

  if (растение.здоровье < растение.максимальноеЗдоровье) {
    const доля = растение.здоровье / растение.максимальноеЗдоровье;
    const цвет = доля > 0.5 ? '#7ed957' : (доля > 0.25 ? '#f2c14e' : '#e8604c');
    полоскаЗдоровья(растение.x, растение.y - 56, 52, доля, цвет);
  }
}


