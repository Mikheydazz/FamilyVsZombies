let номерУровняКолоды = 1;
let выбранныеРастения = [];

/* Колода, с которой игрок начал прошлый уровень. Когда он переходит на
   следующий, эта колода подставляется как основа — что осталось доступным,
   переносится, а чего на новом уровне нет — заменяется. */
let последняяКолода = [];

/** Открывает экран выбора колоды для уровня. */
function открытьВыборКолоды(номер, предвыбор) {
  номерУровняКолоды = ограничитьНомер(номер);
  const уровень = УРОВНИ[номерУровняКолоды - 1];
  const доступные = уровень.персонажи;
  const предел = размерКолоды(уровень);

  /* Откуда берём основу:
     1) явно переданный набор — повтор уровня с той же колодой;
     2) колода с прошлого уровня;
     3) первые доступные растения — первый запуск. */
  let основа = null;

  if (Array.isArray(предвыбор) && предвыбор.length > 0) {
    основа = предвыбор.filter(function (тип) { return доступные.indexOf(тип) !== -1; });
  } else if (последняяКолода.length > 0) {
    основа = последняяКолода.filter(function (тип) { return доступные.indexOf(тип) !== -1; });
  }

  if (!основа || основа.length === 0) {
    основа = доступные.slice(0, предел);
  }

  // Что перенеслось — берём в этом же порядке, не больше предела
  выбранныеРастения = основа.slice(0, предел);

  /* Если после переноса не хватает до предела (на новом уровне колода
     больше или часть растений ещё не открыта) — добираем по порядку
     из доступных на уровне. */
  for (const тип of доступные) {
    if (выбранныеРастения.length >= предел) break;
    if (выбранныеРастения.indexOf(тип) === -1) выбранныеРастения.push(тип);
  }

  вМеню = true;
  скрытьОкноСообщения();
  меню.classList.add('скрыто');

  построитьСписокРастений();
  обновитьПодписиКолоды();
  колода.classList.remove('скрыто');
}

