function нарисоватьЗомби(зомби) {
  // Боссы рисуются целиком своими функциями — вместе с полосой здоровья
  if (зомби.вид === 'директор') {
    нарисоватьДиректора(зомби);
    return;
  }
  if (зомби.вид === 'пончик') {
    нарисоватьБоссаПончика(зомби);
    return;
  }
  if (зомби.вид === 'учебник') {
    нарисоватьУчебник(зомби);
    return;
  }

  const шаг = Math.sin(игра.время * (зомби.ускорен ? 8 : 5) + зомби.фаза) * 3;
  const наклон = зомби.атакует ? 6 : 0;

  контекст.save();
  контекст.translate(зомби.x, зомби.y + (зомби.атакует ? 0 : Math.abs(шаг) * 0.4));
  контекст.scale(-1, 1);        // зомби смотрит влево, в сторону дома
  if (зомби.вид === 'талкус') контекст.scale(зомби.масштаб, зомби.масштаб);
  контекст.translate(наклон, 0);

  контекст.beginPath();
  контекст.ellipse(0, 34, 24, 7, 0, 0, Math.PI * 2);
  контекст.fillStyle = 'rgba(0, 0, 0, 0.2)';
  контекст.fill();

  if (зомби.вспышка > 0) контекст.globalAlpha = 0.6;

  const рубашка = (зомби.вид === 'старик') ? '#7c7360'
    : (зомби.вид === 'талкус') ? '#6a3a2a'
    : (зомби.вид === 'винтер') ? '#3f7a86'
    : (зомби.вид === 'плавающий') ? '#2f6f9a'
    : (зомби.вид === 'кроули') ? '#5a4a2e' : '#6f7a5a';
  const тень = (зомби.вид === 'старик') ? '#665e4d'
    : (зомби.вид === 'талкус') ? '#512c1f'
    : (зомби.вид === 'винтер') ? '#2f5d68'
    : (зомби.вид === 'плавающий') ? '#24557a'
    : (зомби.вид === 'кроули') ? '#43361f' : '#5c6649';
  const кожа = (зомби.вид === 'талкус') ? '#8a9a6e'
    : (зомби.вид === 'винтер') ? '#7fb8a8'
    : (зомби.вид === 'плавающий') ? '#8fb6c8'
    : (зомби.вид === 'кроули') ? '#a07846' : '#9db383';
  нарисоватьТело(шаг, рубашка, кожа, тень);

  // Плавающий: спасательный круг
  if (зомби.вид === 'плавающий') {
    контекст.beginPath();
    контекст.ellipse(0, 14, 25, 10, 0, 0, Math.PI * 2);
    контекст.fillStyle = '#ffbe5a';
    контекст.fill();
    контекст.strokeStyle = '#d94f3d';
    контекст.lineWidth = 3;
    контекст.stroke();

    контекст.beginPath();
    контекст.moveTo(-25, 14); контекст.lineTo(-16, 14);
    контекст.moveTo(-12, 8); контекст.lineTo(-6, 16);
    контекст.moveTo(12, 8); контекст.lineTo(6, 16);
    контекст.moveTo(25, 14); контекст.lineTo(16, 14);
    контекст.strokeStyle = '#d94f3d';
    контекст.lineWidth = 3.5;
    контекст.stroke();
  }

  // Любой водный зомби расходится кругами по воде
  if (зомби.водный) {
    for (let i = 0; i < 2; i++) {
      const волна = (игра.время * 0.8 + i * 0.5 + зомби.фаза) % 1;
      контекст.globalAlpha = (1 - волна) * 0.45;
      контекст.beginPath();
      контекст.ellipse(0, 30, 18 + волна * 26, 6 + волна * 8, 0, 0, Math.PI * 2);
      контекст.strokeStyle = '#d8f2ff';
      контекст.lineWidth = 2;
      контекст.stroke();
    }
    контекст.globalAlpha = зомби.вспышка > 0 ? 0.6 : 1;
  }

  // Спинной плавник рыбы-человека
  if (зомби.вид === 'винтер') {
    контекст.beginPath();
    контекст.moveTo(17, -14);
    контекст.lineTo(34, 3);
    контекст.lineTo(17, 13);
    контекст.closePath();
    контекст.fillStyle = '#4fa0a8';
    контекст.fill();
    контекст.strokeStyle = '#2b6470';
    контекст.lineWidth = 1.5;
    контекст.stroke();
  }

  контекст.save();
  контекст.translate(2, -26);

  if (зомби.вид === 'старик') {
    нарисоватьГоловуЗомби('#a8b892', '#d8d8d0');
    контекст.strokeStyle = 'rgba(90, 100, 70, 0.8)';
    контекст.lineWidth = 1.4;
    контекст.beginPath();
    контекст.moveTo(-9, -6); контекст.lineTo(-4, -4);
    контекст.moveTo(7, -6); контекст.lineTo(12, -4);
    контекст.stroke();
  } else if (зомби.вид === 'талкус') {
    нарисоватьГоловуЗомби('#8a9a6e', '#3a2a18');
    // Густая борода
    контекст.beginPath();
    контекст.arc(2, 9, 12, Math.PI * 0.05, Math.PI * 0.95);
    контекст.closePath();
    контекст.fillStyle = '#3a2a18';
    контекст.fill();
    // Злые брови
    контекст.strokeStyle = '#2a1c10';
    контекст.lineWidth = 3;
    контекст.beginPath();
    контекст.moveTo(-3, -8); контекст.lineTo(7, -5);
    контекст.moveTo(8, -6); контекст.lineTo(16, -9);
    контекст.stroke();
  } else if (зомби.вид === 'винтер') {
    нарисоватьГоловуЗомби('#7fb8a8', '#12414a');
    // Плавник на макушке
    контекст.beginPath();
    контекст.moveTo(-7, -13);
    контекст.lineTo(2, -31);
    контекст.lineTo(11, -12);
    контекст.closePath();
    контекст.fillStyle = '#4fa0a8';
    контекст.fill();
    контекст.strokeStyle = '#2b6470';
    контекст.lineWidth = 1.5;
    контекст.stroke();
    // Жабры
    контекст.strokeStyle = 'rgba(24, 62, 70, 0.8)';
    контекст.lineWidth = 1.8;
    контекст.beginPath();
    контекст.moveTo(-11, -3); контекст.lineTo(-11, 7);
    контекст.moveTo(-7, -4); контекст.lineTo(-7, 8);
    контекст.stroke();
  } else if (зомби.вид === 'кроули') {
    нарисоватьГоловуСобаки();
  } else {
    нарисоватьГоловуЗомби('#9db383', '#2f3a24');
  }

  // Дорожный конус поверх головы
  if (зомби.вид === 'конус') {
    контекст.beginPath();
    контекст.moveTo(-14, -6);
    контекст.lineTo(2, -40);
    контекст.lineTo(14, -6);
    контекст.closePath();
    контекст.fillStyle = '#e8792b';
    контекст.fill();
    контекст.fillStyle = 'rgba(255, 255, 255, 0.85)';
    контекст.fillRect(-11, -14, 22, 5);
    контекст.fillRect(-7, -24, 15, 5);
    контекст.strokeStyle = '#a8501a';
    контекст.lineWidth = 2;
    контекст.beginPath();
    контекст.moveTo(-14, -6); контекст.lineTo(2, -40); контекст.lineTo(14, -6);
    контекст.stroke();
  }
  контекст.restore();

  // Палка старика
  if (зомби.вид === 'старик') {
    скруглённыйПрямоугольник(24, -6, 6, 44, 3, '#8a6a3a');
    контекст.beginPath();
    контекст.arc(24, -6, 7, Math.PI * 0.5, Math.PI * 1.5);
    контекст.strokeStyle = '#8a6a3a';
    контекст.lineWidth = 6;
    контекст.stroke();
  }

  // Книжка-щит учителя
  if (зомби.вид === 'учитель') нарисоватьКнижкуУчителя(зомби);

  if (зомби.вспышка > 0) {
    контекст.globalAlpha = ограничить(зомби.вспышка * 3, 0, 0.55);
    круг(0, -8, 34, '#ffffff');
  }
  контекст.globalAlpha = 1;

  // Разгорячённый старик подсвечивается
  if (зомби.ускорен) {
    контекст.globalAlpha = 0.28 + Math.sin(игра.время * 12) * 0.1;
    круг(0, -6, 38, '#ff7a3d');
    контекст.globalAlpha = 1;
  }

  контекст.restore();

  // Полоска здоровья с отметкой половины: после неё старик ускоряется
  if (зомби.здоровье < зомби.максимальноеЗдоровье) {
    const доля = зомби.здоровье / зомби.максимальноеЗдоровье;
    const цвет = доля > 0.5 ? '#7ed957' : (доля > 0.25 ? '#f2c14e' : '#e8604c');
    const полоскаY = (зомби.вид === 'талкус') ? зомби.y - 72 : зомби.y - 56;
    const ширинаПолоски = (зомби.вид === 'талкус') ? 64 : 50;
    полоскаЗдоровья(зомби.x, полоскаY, ширинаПолоски, доля, цвет);

    if (зомби.вид === 'старик') {
      контекст.fillStyle = 'rgba(255, 255, 255, 0.9)';
      контекст.fillRect(зомби.x - 1, зомби.y - 57, 2, 9);
    }
  }
}


