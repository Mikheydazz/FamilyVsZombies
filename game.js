function составитьРасписание(уровень) {
  const расписание = [];
  let момент = уровень.первыйВраг;

  for (let i = 0; i < уровень.состав.length; i++) {
    расписание.push({
      время: момент,
      ряд: РЯДЫ_ПОЯВЛЕНИЯ[i % РЯДЫ_ПОЯВЛЕНИЯ.length],
      вид: уровень.состав[i],
      использовано: false
    });
    момент += уровень.шаг(i);
  }
  return расписание;
}

