/** Подсвечивает область 3×3 вокруг каждого танцующего кактуса. */
function нарисоватьОбластьПриманки() {
  for (const растение of игра.растения) {
    if (растение.тип !== 'кактус') continue;

    const левая = ограничить(растение.колонка - РАДИУС_ПРИМАНКИ_КАКТУСА, 0, ЧИСЛО_КОЛОНОК - 1);
    const правая = ограничить(растение.колонка + РАДИУС_ПРИМАНКИ_КАКТУСА, 0, ЧИСЛО_КОЛОНОК - 1);
    const верхний = ограничить(растение.ряд - РАДИУС_ПРИМАНКИ_КАКТУСА, 0, ЧИСЛО_РЯДОВ - 1);
    const нижний = ограничить(растение.ряд + РАДИУС_ПРИМАНКИ_КАКТУСА, 0, ЧИСЛО_РЯДОВ - 1);

    const x = ПОЛЕ_X + левая * КЛЕТКА_ШИРИНА;
    const y = ПОЛЕ_Y + верхний * КЛЕТКА_ВЫСОТА;
    const ширина = (правая - левая + 1) * КЛЕТКА_ШИРИНА;
    const высота = (нижний - верхний + 1) * КЛЕТКА_ВЫСОТА;
    const пульс = 0.5 + 0.5 * Math.sin(игра.время * 4 + растение.фаза);

    контекст.save();
    контекст.globalAlpha = 0.1 + 0.08 * пульс;
    контекст.fillStyle = '#8ef0a8';
    контекст.fillRect(x, y, ширина, высота);

    контекст.globalAlpha = 0.5 + 0.3 * пульс;
    контекст.setLineDash([10, 8]);
    контекст.lineWidth = 3;
    контекст.strokeStyle = '#b6ffcb';
    контекст.strokeRect(x + 2, y + 2, ширина - 4, высота - 4);
    контекст.restore();
  }
}

