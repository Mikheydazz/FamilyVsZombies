function нарисоватьСферу(сфера) {
  const пульс = 1 + Math.sin(игра.время * 6 + сфера.фаза) * 0.06;
  const мигание = (!сфера.падает && сфера.жизнь < 3)
    ? (0.45 + 0.55 * Math.abs(Math.sin(игра.время * 8))) : 1;

  контекст.save();
  контекст.globalAlpha = мигание;
  контекст.translate(сфера.x, сфера.y);
  контекст.scale(пульс, пульс);

  const ореол = контекст.createRadialGradient(0, 0, 4, 0, 0, сфера.радиус + 12);
  ореол.addColorStop(0, 'rgba(255, 226, 110, 0.75)');
  ореол.addColorStop(1, 'rgba(255, 210, 70, 0)');
  контекст.beginPath();
  контекст.arc(0, 0, сфера.радиус + 12, 0, Math.PI * 2);
  контекст.fillStyle = ореол;
  контекст.fill();

  контекст.save();
  контекст.rotate(игра.время * 0.9 + сфера.фаза);
  контекст.fillStyle = '#ffd83d';
  for (let i = 0; i < 8; i++) {
    контекст.rotate(Math.PI / 4);
    контекст.fillRect(-3, -сфера.радиус - 7, 6, 8);
  }
  контекст.restore();

  круг(0, 0, сфера.радиус, '#ffd83d');
  круг(-сфера.радиус * 0.3, -сфера.радиус * 0.3, сфера.радиус * 0.42, 'rgba(255, 255, 255, 0.55)');

  контекст.beginPath();
  контекст.moveTo(4, -12);
  контекст.lineTo(-5, 1);
  контекст.lineTo(0, 1);
  контекст.lineTo(-3, 13);
  контекст.lineTo(7, -1);
  контекст.lineTo(2, -1);
  контекст.closePath();
  контекст.fillStyle = '#ff8f1f';
  контекст.fill();

  контекст.restore();
}

