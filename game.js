let времяПоследнегоКадра = 0;

function игровойЦикл(меткаВремени) {
  if (!времяПоследнегоКадра) времяПоследнегоКадра = меткаВремени;

  // Ограничиваем шаг, чтобы после сворачивания окна игра не «прыгала»
  const дт = Math.min((меткаВремени - времяПоследнегоКадра) / 1000, 0.05);
  времяПоследнегоКадра = меткаВремени;

  // Пока открыто меню — игра не обновляется и не рисуется
  if (!вМеню && игра) {
    обновить(дт);
    нарисовать();
  }

  requestAnimationFrame(игровойЦикл);
}

// Точка входа: сначала показываем главное меню
показатьМеню();
requestAnimationFrame(игровойЦикл);
