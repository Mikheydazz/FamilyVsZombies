function круг(x, y, радиус, цвет) {
  контекст.beginPath();
  контекст.arc(x, y, радиус, 0, Math.PI * 2);
  контекст.fillStyle = цвет;
  контекст.fill();
}

function путьСкруглённогоПрямоугольника(x, y, ширина, высота, радиус) {
  const r = Math.min(радиус, ширина / 2, высота / 2);
  контекст.beginPath();
  контекст.moveTo(x + r, y);
  контекст.arcTo(x + ширина, y, x + ширина, y + высота, r);
  контекст.arcTo(x + ширина, y + высота, x, y + высота, r);
  контекст.arcTo(x, y + высота, x, y, r);
  контекст.arcTo(x, y, x + ширина, y, r);
  контекст.closePath();
}

function скруглённыйПрямоугольник(x, y, ширина, высота, радиус, цвет) {
  путьСкруглённогоПрямоугольника(x, y, ширина, высота, радиус);
  контекст.fillStyle = цвет;
  контекст.fill();
}

function надпись(строка, x, y, размер, цвет, выравнивание, жирный) {
  контекст.font = (жирный === false ? '' : 'bold ') + размер + 'px "Segoe UI", Arial, sans-serif';
  контекст.fillStyle = цвет;
  контекст.textAlign = выравнивание || 'center';
  контекст.textBaseline = 'middle';
  контекст.fillText(строка, x, y);
}

