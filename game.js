function нарисоватьРастение(растение) {
  контекст.save();
  контекст.translate(растение.x, растение.y);
  контекст.scale(МАСШТАБ_ПЕРСОНАЖА, МАСШТАБ_ПЕРСОНАЖА);

  контекст.beginPath();
  контекст.ellipse(0, 34, 26, 8, 0, 0, Math.PI * 2);
  контекст.fillStyle = 'rgba(0, 0, 0, 0.18)';
  контекст.fill();

  if (растение.вспышка > 0) контекст.globalAlpha = 0.55;

  if (растение.тип === 'алексей') нарисоватьАлексея(игра.время, растение.фаза);
  if (растение.тип === 'софья') нарисоватьСофью(игра.время, растение.фаза);
  if (растение.тип === 'тимофей') нарисоватьТимофея(игра.время, растение.фаза, растение.выстрел);
  if (растение.тип === 'вигголайф') {
    нарисоватьВигголайфа(игра.время, растение.фаза,
      ограничить(растение.запал / ВРЕМЯ_ЗАПАЛА, 0, 1));
  }
  if (растение.тип === 'мелон') нарисоватьМелона(игра.время, растение.фаза, растение.выстрел);
  if (растение.тип === 'заруд') нарисоватьЗаруда(игра.время, растение.фаза, растение.режим);
  if (растение.тип === 'антон') нарисоватьАнтона(игра.время, растение.фаза, растение.выстрел);

  контекст.globalAlpha = 1;

  if (растение.вспышка > 0) {
    контекст.globalAlpha = ограничить(растение.вспышка * 2, 0, 0.5);
    круг(0, -6, 34, '#ff5a4a');
    контекст.globalAlpha = 1;
  }

  контекст.restore();

  if (растение.здоровье < растение.максимальноеЗдоровье) {
    const доля = растение.здоровье / растение.максимальноеЗдоровье;
    const цвет = доля > 0.5 ? '#7ed957' : (доля > 0.25 ? '#f2c14e' : '#e8604c');
    полоскаЗдоровья(растение.x, растение.y - 56, 52, доля, цвет);
  }
}


