/** Водные линии второй главы: синяя гладь с бегущими волнами. */
function нарисоватьВоду() {
  const вода = (игра && игра.уровень && игра.уровень.вода) || [];
  if (!вода.length) return;

  const ширинаПоля = ЧИСЛО_КОЛОНОК * КЛЕТКА_ШИРИНА;

  for (const ряд of вода) {
    const y = ПОЛЕ_Y + ряд * КЛЕТКА_ВЫСОТА;

    // Гладь
    const гладь = контекст.createLinearGradient(0, y, 0, y + КЛЕТКА_ВЫСОТА);
    гладь.addColorStop(0, '#357fbe');
    гладь.addColorStop(0.5, '#2a6ba5');
    гладь.addColorStop(1, '#1e5488');
    контекст.fillStyle = гладь;
    контекст.fillRect(ПОЛЕ_X, y, ширинаПоля, КЛЕТКА_ВЫСОТА);

    // Бегущие волны
    контекст.strokeStyle = 'rgba(190, 235, 255, 0.32)';
    контекст.lineWidth = 2;
    for (let i = 0; i < 3; i++) {
      const волнаY = y + 24 + i * 30;
      const сдвиг = игра.время * 26 + i * 40 + ряд * 17;
      контекст.beginPath();
      for (let x = 0; x <= ширинаПоля; x += 10) {
        const yy = волнаY + Math.sin((x + сдвиг) * 0.028) * 4;
        if (x === 0) контекст.moveTo(ПОЛЕ_X + x, yy);
        else контекст.lineTo(ПОЛЕ_X + x, yy);
      }
      контекст.stroke();
    }

    // Блики у кромки воды
    контекст.fillStyle = 'rgba(255, 255, 255, 0.14)';
    контекст.fillRect(ПОЛЕ_X, y, ширинаПоля, 4);
    контекст.fillRect(ПОЛЕ_X, y + КЛЕТКА_ВЫСОТА - 4, ширинаПоля, 4);
  }
}

