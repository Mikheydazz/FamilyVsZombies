/* ============================ СЕКРЕТНОЕ ОКНО ============================ */

/** Открыто ли сейчас окно чита. */
function окноЧитаОткрыто() {
  return !окноЧита.classList.contains('скрыто');
}

/** Показывает окно чита: подставляет текущее число и ставит фокус. */
function открытьОкноЧита() {
  const прогресс = прочитатьПрогресс();

  полеЧита.value = String(прогресс.открытУровень);
  полеЧита.min = '1';
  полеЧита.max = String(УРОВНИ.length);
  ошибкаЧита.textContent = '';

  окноЧита.classList.remove('скрыто');

  полеЧита.focus();
  полеЧита.select();
}

/** Прячет окно чита. */
function закрытьОкноЧита() {
  окноЧита.classList.add('скрыто');
  ошибкаЧита.textContent = '';
}

/** Читает число из поля, проверяет и записывает в прогресс. */
function применитьЧит() {
  const текст = полеЧита.value.trim();
  const число = Number(текст);

  if (текст === '' || !Number.isFinite(число) || !Number.isInteger(число)) {
    ошибкаЧита.textContent = 'Нужно целое число от 1 до ' + УРОВНИ.length + '.';
    return;
  }

  // Зажимаем в допустимый диапазон: 1…УРОВНИ.length
  const итог = ограничитьНомер(число);

  const прогресс = прочитатьПрогресс();
  прогресс.открытУровень = итог;
  записатьПрогресс(прогресс);

  // Пересобираем кнопки уровней и статистику, экран меню не трогаем
  обновитьКнопкиУровней();

  закрытьОкноЧита();

  // Короткое подтверждение поверх меню
  const подтверждение = document.createElement('p');
  подтверждение.className = 'меню-статистика';
  подтверждение.style.color = '#ffe066';
  подтверждение.textContent = 'Открыто уровней: ' + итог + ' из ' + УРОВНИ.length;
  меню.appendChild(подтверждение);
  setTimeout(function () { подтверждение.remove(); }, 1600);
}

// Кнопки окна
кнопкаЧитаОк.addEventListener('click', применитьЧит);
кнопкаЧитаОтмена.addEventListener('click', закрытьОкноЧита);

// Клик по тёмному фону закрывает, клик по карточке — нет
окноЧита.addEventListener('mousedown', function (событие) {
  if (событие.target === окноЧита) закрытьОкноЧита();
});

// Enter — применить, Escape — отмена. Гасим всплытие, чтобы игра не реагировала.
полеЧита.addEventListener('keydown', function (событие) {
  if (событие.code === 'Enter' || событие.code === 'NumpadEnter') {
    событие.preventDefault();
    событие.stopPropagation();
    применитьЧит();
  }
  if (событие.code === 'Escape') {
    событие.preventDefault();
    событие.stopPropagation();
    закрытьОкноЧита();
  }
});

// Комбинация Shift+L в меню
window.addEventListener('keydown', function (событие) {
  if (!вМеню) return;                  // работает только в меню
  if (!событие.shiftKey) return;
  if (событие.code !== 'KeyL') return;

  событие.preventDefault();

  if (окноЧитаОткрыто()) return;       // уже открыто — не переоткрываем
  открытьОкноЧита();
});

