function нарисоватьПолосуДождя(растение) {
  const левая = Math.max(0, растение.колонка - ПОЛОСА_ДОЖДЯ_ДАШИ);
  const правая = Math.min(ЧИСЛО_КОЛОНОК - 1, растение.колонка + ПОЛОСА_ДОЖДЯ_ДАШИ);
  const левыйX = ПОЛЕ_X + левая * КЛЕТКА_ШИРИНА;
  const ширина = (правая - левая + 1) * КЛЕТКА_ШИРИНА;
  const высота = ПОЛЕ_НИЖНИЙ - ПОЛЕ_Y;

  const доля = ограничить(растение.таймер / (растение.длительностьДождя || ДЛИТЕЛЬНОСТЬ_ДОЖДЯ_ДАШИ), 0, 1);
  const прозрачность = доля < 0.12
    ? доля / 0.12
    : (доля > 0.85 ? ограничить((1 - доля) / 0.15, 0, 1) : 1);

  контекст.save();

  // Светящаяся полоса
  контекст.globalAlpha = 0.12 * прозрачность;
  контекст.fillStyle = '#fff6c0';
  контекст.fillRect(левыйX, ПОЛЕ_Y, ширина, высота);

  // Падающие кресты
  контекст.globalAlpha = 0.92 * прозрачность;
  const число = Math.max(8, Math.round(ширина / 13));
  for (let i = 0; i < число; i++) {
    const смещение = псевдоСлучайное(i * 7.13) * ширина;
    const фаза = псевдоСлучайное(i * 3.71);
    const падение = (игра.время * 470 + фаза * высота * 1.7) % (высота + 70);
    нарисоватьКрест(левыйX + смещение, ПОЛЕ_Y + падение - 35,
      8 + псевдоСлучайное(i * 1.37) * 5);
  }

  контекст.restore();
}

