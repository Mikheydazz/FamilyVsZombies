/** Приводит колоду к списку доступных на уровне растений (не длиннее размера колоды). */
function нормализоватьКолоду(уровень, колода) {
  const доступные = уровень.персонажи;
  const итог = [];

  if (Array.isArray(колода)) {
    for (const тип of колода) {
      if (доступные.indexOf(тип) !== -1 && итог.indexOf(тип) === -1) итог.push(тип);
    }
  }

  const предел = размерКолоды(уровень);

  // Если колода не задана или пуста — берём первых персонажей уровня
  if (итог.length === 0) return доступные.slice(0, предел);
  return итог.slice(0, предел);
}

