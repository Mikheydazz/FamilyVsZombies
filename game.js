function центрКлетки(колонка, ряд) {
  return {
    x: ПОЛЕ_X + колонка * КЛЕТКА_ШИРИНА + КЛЕТКА_ШИРИНА / 2,
    y: ПОЛЕ_Y + ряд * КЛЕТКА_ВЫСОТА + КЛЕТКА_ВЫСОТА / 2
  };
}

function клеткаПоКоординатам(x, y) {
  if (x < ПОЛЕ_X || x >= ПОЛЕ_ПРАВЫЙ || y < ПОЛЕ_Y || y >= ПОЛЕ_НИЖНИЙ) return null;
  return {
    колонка: Math.floor((x - ПОЛЕ_X) / КЛЕТКА_ШИРИНА),
    ряд: Math.floor((y - ПОЛЕ_Y) / КЛЕТКА_ВЫСОТА)
  };
}

function естьРастение(колонка, ряд) {
  return игра.растения.some(function (р) { return р.колонка === колонка && р.ряд === ряд; });
}

/** Убирает персонажа с клетки молотом. Возвращает true, если персонаж был. */
function удалитьПерсонажа(колонка, ряд) {
  const индекс = игра.растения.findIndex(function (р) {
    return р.колонка === колонка && р.ряд === ряд;
  });
  if (индекс === -1) return false;

  const растение = игра.растения[индекс];
  добавитьЭффект(растение.x, растение.y, 'rgba(200, 170, 90, 0.85)');
  добавитьВсплывающийТекст(растение.x, растение.y - 40, 'Убран!', '#ffd08a');
  игра.растения.splice(индекс, 1);
  return true;
}

function ограничить(значение, минимум, максимум) {
  return Math.max(минимум, Math.min(максимум, значение));
}

function случайноеЧисло(минимум, максимум) {
  return минимум + Math.random() * (максимум - минимум);
}

/** Ближайший к дому персонаж в ряду зомби — тот, что первым попадётся. */
function найтиЦельДляУкуса(зомби) {
  let цель = null;
  for (const растение of игра.растения) {
    if (растение.ряд !== зомби.ряд) continue;
    const расстояние = зомби.x - растение.x;
    if (расстояние >= 0 && расстояние <= РАССТОЯНИЕ_УКУСА) {
      if (!цель || растение.x > цель.x) цель = растение;
    }
  }
  return цель;
}

/** Есть ли живой зомби в ряду правее точки x (персонажи стреляют вправо). */
function естьЗомбиВпереди(ряд, x) {
  return игра.зомби.some(function (з) { return з.ряд === ряд && з.x > x + 8; });
}

/** Ближайший к дому зомби — тот, что дальше всех прошёл влево. */
function найтиЦельДляДыни() {
  let цель = null;
  for (const зомби of игра.зомби) {
    if (!цель || зомби.x < цель.x) цель = зомби;
  }
  return цель;
}

/** Ближайший зомби в ряду правее точки x (для Заруда). */
function найтиЗомбиВРадиусе(ряд, x, радиус) {
  let цель = null;
  for (const зомби of игра.зомби) {
    if (зомби.ряд !== ряд) continue;
    const расстояние = зомби.x - x;
    if (расстояние > 0 && расстояние <= радиус) {
      if (!цель || зомби.x < цель.x) цель = зомби;
    }
  }
  return цель;
}

/** Ближайший зомби в ряду правее точки x (для бобра Антона). */
function найтиЦельДляБобра(ряд, x) {
  let цель = null;
  for (const зомби of игра.зомби) {
    if (зомби.ряд !== ряд || зомби.x <= x) continue;
    if (!цель || зомби.x < цель.x) цель = зомби;
  }
  return цель;
}

