function координатыСобытия(событие) {
  const прямоугольник = канвас.getBoundingClientRect();
  return {
    x: (событие.clientX - прямоугольник.left) * (ШИРИНА_ЭКРАНА / прямоугольник.width),
    y: (событие.clientY - прямоугольник.top) * (ВЫСОТА_ЭКРАНА / прямоугольник.height)
  };
}

function попаданиеВПрямоугольник(x, y, прямоугольник) {
  return x >= прямоугольник.x && x <= прямоугольник.x + прямоугольник.ширина &&
         y >= прямоугольник.y && y <= прямоугольник.y + прямоугольник.высота;
}

function картаПоКоординатам(x, y) {
  for (const карта of игра.карты) {
    if (попаданиеВПрямоугольник(x, y, карта)) return карта.тип;
  }
  return null;
}

function выбратьКарту(тип) {
  const описание = ПЕРСОНАЖИ[тип];
  if (игра.энергия < описание.стоимость) {
    добавитьВсплывающийТекст(ШИРИНА_ЭКРАНА / 2, ВЫСОТА_HUD + 30,
      'Не хватает энергии: нужно ' + описание.стоимость, '#ffb199');
    return;
  }
  if (игра.перезарядка[тип] > 0) {
    добавитьВсплывающийТекст(ШИРИНА_ЭКРАНА / 2, ВЫСОТА_HUD + 30,
      описание.название + ' ещё отдыхает', '#ffd08a');
    return;
  }
  игра.выбраннаяКарта = (игра.выбраннаяКарта === тип) ? null : тип;
  игра.молотВыбран = false;
}

function обработатьКлик(x, y) {
  if (игра.состояние !== 'игра') return;

  if (попаданиеВПрямоугольник(x, y, КНОПКА_ПАУЗЫ)) {
    игра.пауза = !игра.пауза;
    return;
  }

  if (игра.пауза) return;

  // Молот: включаем/выключаем режим удаления персонажей
  if (попаданиеВПрямоугольник(x, y, КНОПКА_МОЛОТА)) {
    игра.молотВыбран = !игра.молотВыбран;
    if (игра.молотВыбран) игра.выбраннаяКарта = null;
    return;
  }

  const карта = картаПоКоординатам(x, y);
  if (карта) {
    выбратьКарту(карта);
    return;
  }

  if (y < ВЫСОТА_HUD) return;

  // Сбор энергии проверяем раньше посадки — сфера важнее
  if (попытатьсяСобратьСферу(x, y)) return;

  if (игра.молотВыбран) {
    const клетка = клеткаПоКоординатам(x, y);
    if (клетка && удалитьПерсонажа(клетка.колонка, клетка.ряд)) {
      игра.молотВыбран = false;   // как лопата: одна уборка за раз
    }
    return;
  }

  if (игра.выбраннаяКарта) {
    const клетка = клеткаПоКоординатам(x, y);
    if (клетка && посадитьПерсонажа(игра.выбраннаяКарта, клетка.колонка, клетка.ряд)) {
      if (игра.энергия < ПЕРСОНАЖИ[игра.выбраннаяКарта].стоимость) {
        игра.выбраннаяКарта = null;
      }
    }
  }
}

