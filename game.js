/** Сколько растений нужно взять на текущем уровне. */
function цельКолоды() {
  const уровень = УРОВНИ[номерУровняКолоды - 1];
  return размерКолоды(уровень);
}

/** Добавляет или убирает растение из колоды. */
function переключитьРастение(тип) {
  const позиция = выбранныеРастения.indexOf(тип);

  if (позиция !== -1) {
    выбранныеРастения.splice(позиция, 1);
  } else if (выбранныеРастения.length < цельКолоды()) {
    выбранныеРастения.push(тип);
  }

  обновитьВидКарточек();
  обновитьПодписиКолоды();
}

/** Подсвечивает выбранные карточки. */
function обновитьВидКарточек() {
  const карточки = списокРастений.querySelectorAll('.карточка-растения');
  for (const карточка of карточки) {
    const выбрана = выбранныеРастения.indexOf(карточка.dataset.тип) !== -1;
    карточка.classList.toggle('выбрана', выбрана);
  }
}

