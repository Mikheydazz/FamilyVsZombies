const КЛЮЧ_ХРАНИЛИЩА = 'familyDefence.прогресс';

const ПУСТОЙ_ПРОГРЕСС = { побед: 0, поражений: 0, открытУровень: 1 };

function ограничитьНомер(номер) {
  return Math.max(1, Math.min(УРОВНИ.length, номер));
}

function прочитатьПрогресс() {
  try {
    const данные = JSON.parse(localStorage.getItem(КЛЮЧ_ХРАНИЛИЩА));
    if (!данные || typeof данные !== 'object') return Object.assign({}, ПУСТОЙ_ПРОГРЕСС);
    return {
      побед: Number(данные.побед) || 0,
      поражений: Number(данные.поражений) || 0,
      открытУровень: ограничитьНомер(Number(данные.открытУровень) || 1)
    };
  } catch (ошибка) {
    return Object.assign({}, ПУСТОЙ_ПРОГРЕСС);
  }
}

function записатьПрогресс(прогресс) {
  try {
    localStorage.setItem(КЛЮЧ_ХРАНИЛИЩА, JSON.stringify(прогресс));
  } catch (ошибка) {
    // Приватный режим браузера — играем без сохранения.
  }
}


