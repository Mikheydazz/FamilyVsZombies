function нарисоватьПодсветкуКлетки() {
  if (игра.состояние !== 'игра') return;

  const клетка = клеткаПоКоординатам(игра.мышь.x, игра.мышь.y);
  if (!клетка || !игра.выбраннаяКарта) return;

  const тип = игра.выбраннаяКарта;
  const описание = ПЕРСОНАЖИ[тип];
  const занята = естьРастение(клетка.колонка, клетка.ряд);
  const можно = !занята && игра.энергия >= описание.стоимость &&
    (игра.перезарядка[тип] || 0) <= 0;

  const x = ПОЛЕ_X + клетка.колонка * КЛЕТКА_ШИРИНА;
  const y = ПОЛЕ_Y + клетка.ряд * КЛЕТКА_ВЫСОТА;

  контекст.fillStyle = можно ? 'rgba(255, 255, 255, 0.3)' : 'rgba(220, 70, 60, 0.32)';
  контекст.fillRect(x, y, КЛЕТКА_ШИРИНА, КЛЕТКА_ВЫСОТА);
  контекст.strokeStyle = можно ? 'rgba(255, 255, 255, 0.85)' : 'rgba(255, 110, 100, 0.85)';
  контекст.lineWidth = 3;
  контекст.strokeRect(x + 2, y + 2, КЛЕТКА_ШИРИНА - 4, КЛЕТКА_ВЫСОТА - 4);

  if (можно) {
    const центр = центрКлетки(клетка.колонка, клетка.ряд);
    контекст.save();
    контекст.globalAlpha = 0.5;
    контекст.translate(центр.x, центр.y + СМЕЩЕНИЕ_ПЕРСОНАЖА);
    контекст.scale(МАСШТАБ_ПЕРСОНАЖА, МАСШТАБ_ПЕРСОНАЖА);
    нарисоватьПортрет(тип, 0, 0, 1);
    контекст.restore();
  }
}

